using Keeptrack.Domain.Models;
using Riok.Mapperly.Abstractions;

namespace Keeptrack.WebApi.Mappers;

[Mapper(EnumMappingStrategy = EnumMappingStrategy.ByName)]
[UseStaticMapper(typeof(CommonDtoMappings))]
public partial class HouseDtoMapper : IDtoMapper<HouseDto, HouseModel>
{
    // MapValue rather than MapperIgnoreTarget, since OwnerId is required (see BookDtoMapper)
    [MapValue(nameof(HouseModel.OwnerId), "")]
    public partial HouseModel ToModel(HouseDto dto);

    [MapperIgnoreSource(nameof(HouseModel.OwnerId))]
    public partial HouseDto ToDto(HouseModel model);

    /// <summary>
    /// The DTO's property type is nullable where the model's is required, so like <c>CarDtoMapper</c> a hand-written fallback for null wraps the generated ByName conversion.
    /// </summary>
    [UserMapping]
    private Domain.Models.PropertyType ToRequiredPropertyType(Contracts.Dto.PropertyType? value)
    {
        return value.HasValue ? MapPropertyType(value.Value) : default;
    }

    private partial Domain.Models.PropertyType MapPropertyType(Contracts.Dto.PropertyType value);
}
